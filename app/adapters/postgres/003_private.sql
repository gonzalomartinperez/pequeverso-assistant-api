-- Separate private application state. No conversation or visitor data enters knowledge.*.
CREATE SCHEMA IF NOT EXISTS assistant_private;
CREATE TABLE IF NOT EXISTS assistant_private.sessions (
    id text PRIMARY KEY,
    secret_digest bytea NOT NULL UNIQUE,
    csrf_token text NOT NULL,
    created_at timestamptz NOT NULL,
    last_active_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS private_sessions_expiry ON assistant_private.sessions(expires_at);
CREATE TABLE IF NOT EXISTS assistant_private.messages (
    seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id text NOT NULL UNIQUE,
    session_id text NOT NULL REFERENCES assistant_private.sessions(id) ON DELETE CASCADE,
    role text NOT NULL CHECK(role IN ('user','assistant')),
    content text NOT NULL,
    details text NOT NULL,
    created_at timestamptz NOT NULL,
    UNIQUE(session_id,id)
);
CREATE INDEX IF NOT EXISTS private_messages_session ON assistant_private.messages(session_id,seq);
CREATE TABLE IF NOT EXISTS assistant_private.runs (
    id text PRIMARY KEY,
    session_id text NOT NULL REFERENCES assistant_private.sessions(id) ON DELETE CASCADE,
    idempotency_key text NOT NULL,
    request_hash text NOT NULL,
    state text NOT NULL CHECK(state IN ('active','completed','failed','cancelled')),
    assistant_message_id text,
    created_at timestamptz NOT NULL,
    UNIQUE(session_id,idempotency_key),
    FOREIGN KEY(session_id,assistant_message_id) REFERENCES assistant_private.messages(session_id,id)
);
CREATE UNIQUE INDEX IF NOT EXISTS private_one_active_run ON assistant_private.runs(session_id) WHERE state='active';
CREATE TABLE IF NOT EXISTS assistant_private.spend_ledger (
    run_id text PRIMARY KEY,
    month text NOT NULL,
    day text NOT NULL,
    reserved_micro bigint NOT NULL CHECK(reserved_micro>=0),
    actual_micro bigint CHECK(actual_micro>=0),
    model text,
    input_tokens bigint CHECK(input_tokens>=0),
    output_tokens bigint CHECK(output_tokens>=0),
    cached_input_tokens bigint CHECK(cached_input_tokens>=0),
    cache_write_tokens bigint CHECK(cache_write_tokens>=0),
    reasoning_tokens bigint CHECK(reasoning_tokens>=0),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','settled','unreported')),
    settled_at timestamptz
);
CREATE INDEX IF NOT EXISTS private_ledger_month ON assistant_private.spend_ledger(month);
CREATE INDEX IF NOT EXISTS private_ledger_day ON assistant_private.spend_ledger(day);
CREATE INDEX IF NOT EXISTS private_ledger_status ON assistant_private.spend_ledger(status);
CREATE TABLE IF NOT EXISTS assistant_private.rate_counters (
    key text NOT NULL,
    window_start bigint NOT NULL,
    count bigint NOT NULL CHECK(count>=0),
    PRIMARY KEY(key,window_start)
);
CREATE TABLE IF NOT EXISTS assistant_private.run_metrics (
    run_id text PRIMARY KEY,
    started_at timestamptz NOT NULL,
    ended_at timestamptz NOT NULL,
    day text NOT NULL,
    outcome text NOT NULL CHECK(outcome IN ('completed','failed','cancelled','interrupted','refused')),
    code text,
    model_call boolean NOT NULL,
    replaced boolean NOT NULL,
    language text CHECK(language IN ('es','en')),
    first_delta_ms bigint CHECK(first_delta_ms>=0),
    total_ms bigint NOT NULL CHECK(total_ms>=0)
);
CREATE INDEX IF NOT EXISTS private_run_metrics_started ON assistant_private.run_metrics(started_at);
-- Legacy public snapshots are retained for migration audit, never promoted/indexed implicitly.
CREATE TABLE IF NOT EXISTS assistant_private.legacy_catalog_snapshots (
    sha256 text PRIMARY KEY,
    schema_version bigint NOT NULL,
    source_revision text NOT NULL,
    generated_at timestamptz NOT NULL,
    activated_at timestamptz NOT NULL,
    body bytea NOT NULL
);
CREATE TABLE IF NOT EXISTS assistant_private.legacy_catalog_state (
    id bigint PRIMARY KEY CHECK(id=1),
    active_sha256 text REFERENCES assistant_private.legacy_catalog_snapshots(sha256),
    verified_at timestamptz,
    last_attempt_at timestamptz,
    last_failure text,
    last_failure_at timestamptz
);
CREATE TABLE IF NOT EXISTS assistant_private.sqlite_imports (
    source_sha256 text PRIMARY KEY,
    canonical_sha256 text NOT NULL,
    source_schema_version integer NOT NULL,
    counts jsonb NOT NULL,
    imported_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
