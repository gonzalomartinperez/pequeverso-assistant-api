    assistant_private.runs,assistant_private.rate_counters,assistant_private.run_metrics TO pequeverso_private_runtime;
GRANT SELECT,INSERT,UPDATE ON assistant_private.spend_ledger TO pequeverso_private_runtime,pequeverso_embedding_accounting;
