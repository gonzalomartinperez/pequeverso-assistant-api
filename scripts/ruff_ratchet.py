"""Ruff legacy ratchet (PVA-M2.1): legacy findings may only shrink.

`pyproject.toml` extends `ratchets/ruff-legacy.toml`, whose per-file ignores hide the findings
that existed when the ecosystem rule families were enabled, so `ruff check .` stays at zero for
new code. This script keeps that base honest:

- `ratchets/ruff.json` records legacy counts per file and rule code; any growth fails.
- Every legacy (file, code) entry must still occur; a fixed entry fails until `--write` removes it.
- `--write` regenerates both files from the current findings; it refuses any new entry or growth.

Usage: `python -m scripts.ruff_ratchet` (check) or `python -m scripts.ruff_ratchet --write`.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEGACY = ROOT / "ratchets" / "ruff-legacy.toml"
COUNTS = ROOT / "ratchets" / "ruff.json"
PREFIX = "../"  # patterns in an extended config resolve relative to that file's directory
HEADER = (
    "# Legacy ruff findings (PVA-M2.1). Generated by `python -m scripts.ruff_ratchet --write`;\n"
    "# never add entries by hand. Entries may only shrink (scripts/ruff_ratchet.py).\n"
    "# Paths start with ../ because an extended config resolves patterns from its own directory.\n"
)


def findings() -> list[tuple[str, str]]:
    """Return (repo-relative path, rule code) for every finding with the legacy base disabled."""
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            ".",
            "--output-format=json",
            "--exit-zero",
            "--config",
            "lint.per-file-ignores = {}",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return [
        (Path(item["filename"]).resolve().relative_to(ROOT).as_posix(), item["code"])
        for item in json.loads(result.stdout)
    ]


def load_legacy() -> dict[str, set[str]]:
    """Read the legacy per-file ignores as repo-relative path to rule codes."""
    data = tomllib.loads(LEGACY.read_text(encoding="utf-8"))
    entries = data.get("lint", {}).get("per-file-ignores", {})
    return {path.removeprefix(PREFIX): set(codes) for path, codes in entries.items()}


def load_counts() -> dict[tuple[str, str], int]:
    """Read the committed legacy counts per (repo-relative path, rule code)."""
    data = json.loads(COUNTS.read_text(encoding="utf-8"))
    return {
        (path, code): int(n) for path, codes in data["by_file"].items() for code, n in codes.items()
    }


def check(current: list[tuple[str, str]]) -> list[str]:
    """Compare current findings with the committed ratchet; return problems."""
    problems: list[str] = []
    legacy = load_legacy()
    allowed = load_counts()
    now = Counter(current)
    for path, code in sorted(now):
        if code not in legacy.get(path, set()):
            problems.append(f"{path}: new {code} finding (fix it; legacy entries never grow)")
    problems.extend(
        f"{path}: {code} no longer occurs; run `python -m scripts.ruff_ratchet --write`"
        for path, codes in sorted(legacy.items())
        for code in sorted(codes)
        if (path, code) not in now
    )
    for key in sorted(set(now) | set(allowed)):
        found, limit = now.get(key, 0), allowed.get(key, 0)
        if found > limit:
            problems.append(f"{key[0]}: {found} {key[1]} findings, ratchet allows {limit}")
        elif found < limit:
            problems.append(
                f"{key[0]}: {found} {key[1]} findings, below the ratchet ({limit}); "
                "tighten with --write"
            )
    return problems


def write(current: list[tuple[str, str]], *, init: bool = False) -> None:
    """Regenerate the legacy base and counts; refuse any new entry or any count increase.

    Without `init` the committed counts must exist (fail closed): a deleted ratchet file never
    turns into a fresh baseline that accepts new findings.
    """
    now = Counter(current)
    if not init:
        if not COUNTS.exists():
            raise SystemExit(f"{COUNTS} is missing; refusing to create a new baseline")
        allowed = load_counts()
        grown = sorted(
            f"{path}: {code} {n} > {allowed.get((path, code), 0)}"
            for (path, code), n in now.items()
            if n > allowed.get((path, code), 0)
        )
        if grown:
            raise SystemExit("refusing to grow the legacy ratchet:\n" + "\n".join(grown))
    by_file: dict[str, dict[str, int]] = defaultdict(dict)
    for (path, code), n in sorted(now.items()):
        by_file[path][code] = n
    lines = [HEADER, "[lint.per-file-ignores]"]
    for path, codes in sorted(by_file.items()):
        listed = ", ".join(f'"{code}"' for code in sorted(codes))
        lines.append(f'"{PREFIX}{path}" = [{listed}]')
    LEGACY.write_text("\n".join(lines) + "\n", encoding="utf-8")
    per_code = Counter(code for _, code in current)
    COUNTS.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "description": "Legacy ruff findings; every count only decreases (PVA-M2.1).",
                "target": "0 for every code by PVA-M4.11",
                "total": sum(per_code.values()),
                "findings": dict(sorted(per_code.items())),
                "by_file": by_file,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def main(argv: list[str] | None = None) -> int:
    """Run the ratchet check or regenerate the ratchet files."""
    parser = argparse.ArgumentParser(
        description="Ruff legacy ratchet: legacy findings only shrink."
    )
    parser.add_argument("--write", action="store_true", help="regenerate the ratchet files")
    parser.add_argument(
        "--init", action="store_true", help="with --write: create the first baseline (review only)"
    )
    args = parser.parse_args(argv)
    current = findings()
    if args.write:
        write(current, init=args.init)
        print(f"ruff ratchet written: {len(current)} legacy findings")
        return 0
    problems = check(current)
    for problem in problems:
        print(problem, file=sys.stderr)
    if not problems:
        print(f"ruff ratchet ok: {len(current)} legacy findings, none new")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
